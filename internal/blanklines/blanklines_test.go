func checkSource(t *testing.T, src string) []finding {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "x.go", src, parser.ParseComments)
	require.NoError(t, err)
	return check(fset, f, []byte(src))
}

func writeFile(t *testing.T, root, rel, src string) {
	t.Helper()
	path := filepath.Join(root, rel)
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(src), 0o600))
}

func TestCheck(t *testing.T) {
	t.Run("a blank line in a function body is found", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc Run() {\n\ta := 1\n\n\t_ = a\n}\n")
		assert.Equal(t, []finding{{Line: 5, Func: "Run"}}, got)
	})
	t.Run("a blank line in a method is named Recv.Name", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc (s *Store) Save() {\n\ta := 1\n\n\t_ = a\n}\n")
		assert.Equal(t, []finding{{Line: 5, Func: "Store.Save"}}, got)
	})
	t.Run("a blank line in a function literal is found", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc Run() {\n\tf := func() {\n\t\ta := 1\n\n\t\t_ = a\n\t}\n\tf()\n}\n")
		assert.Equal(t, []finding{{Line: 6, Func: "Run"}}, got)
	})
	t.Run("a blank line between functions isn't", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc A() {\n\t_ = 1\n}\n\nfunc B() {\n\t_ = 2\n}\n")
		assert.Empty(t, got)
	})
	t.Run("a blank line in a raw string literal isn't", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc Run() string {\n\treturn `a\n\nb`\n}\n")
		assert.Empty(t, got)
	})
	t.Run("a blank line inside a block comment isn't", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc Run() {\n\t/* a\n\n\tb */\n\t_ = 1\n}\n")
		assert.Empty(t, got)
	})
	t.Run("a body without blank lines has no findings", func(t *testing.T) {
		got := checkSource(t, "package x\n\nfunc Run() {\n\t_ = 1\n}\n")
		assert.Empty(t, got)
	})
}

func TestCheckModule(t *testing.T) {
	t.Run("finds a blank line in a file under a temp root", func(t *testing.T) {
		root := t.TempDir()
		writeFile(t, root, "a.go", "package a\n\nfunc Run() {\n\t_ = 1\n\n\t_ = 2\n}\n")
		writeFile(t, root, "sub/b.go", "package sub\n\nfunc Stop() {\n\t_ = 1\n}\n")
		got, err := checkModule(root)
		require.NoError(t, err)
		assert.Equal(t, map[string][]finding{"a.go": {{Line: 5, Func: "Run"}}}, got)
	})
	t.Run("skips generated files", func(t *testing.T) {
		root := t.TempDir()
		writeFile(t, root, "gen.go", "// Code generated by moq; DO NOT EDIT.\n\npackage gen\n\nfunc Run() {\n\t_ = 1\n\n\t_ = 2\n}\n")
		got, err := checkModule(root)
		require.NoError(t, err)
		assert.Empty(t, got)
	})
	t.Run("skips node_modules and testdata", func(t *testing.T) {
		root := t.TempDir()
		writeFile(t, root, "node_modules/x/x.go", "package x\n\nfunc Run() {\n\t_ = 1\n\n\t_ = 2\n}\n")
		writeFile(t, root, "testdata/y.go", "package y\n\nfunc Run() {\n\t_ = 1\n\n\t_ = 2\n}\n")
		got, err := checkModule(root)
		require.NoError(t, err)
		assert.Empty(t, got)
	})
	t.Run("a file that doesn't parse is an error naming it", func(t *testing.T) {
		root := t.TempDir()
		writeFile(t, root, "bad.go", "package bad\n\nfunc (\n")
		_, err := checkModule(root)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "bad.go")
	})
}

func TestRepository(t *testing.T) {
	findings, err := checkModule("../..")
	require.NoError(t, err)
	var violations []string
	for path, found := range findings {
		if exempt[path] {
			continue
		}
		for _, f := range found {
			violations = append(violations, fmt.Sprintf("%s:%d in %s", path, f.Line, f.Func))
		}
	}
	sort.Strings(violations)
	assert.Empty(t, violations, "remove the blank lines from these function bodies")
	var stale []string
	for path := range exempt {
		if _, ok := findings[path]; !ok {
			stale = append(stale, path)
		}
	}
	sort.Strings(stale)
	assert.Empty(t, stale, "remove these files from exempt")
}
